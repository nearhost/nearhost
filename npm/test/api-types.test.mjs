import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const file = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', 'api', 'ts', 'index.d.ts');

test('generated API types exist and cover the schema', () => {
  assert.ok(existsSync(file), 'api/ts/index.d.ts is missing; run make api-types');
  const src = readFileSync(file, 'utf8');
  assert.ok(src.startsWith('/**\n * This file was auto-generated by openapi-typescript.'), 'generator header missing');
  assert.match(src, /export interface paths \{/);
  assert.match(src, /"\/v1\/state"/);
  assert.match(src, /export interface components \{/);
  assert.match(src, /\bEnvelope: \{/);
});
