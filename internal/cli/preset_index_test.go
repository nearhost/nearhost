package cli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/nearhost/nearhost/internal/registry"
)

func TestPresetIndexDescribesEveryPreset(t *testing.T) {
	out, err := execute(t, newPresetCmd(presetBackend{}), "preset", "index", testPresetsDir(), "--ref", "3f2c1ab9d0e4")
	if err != nil {
		t.Fatalf("preset index: %v\n%s", err, out)
	}
	if !strings.HasPrefix(out, "# Generated by `nearhost preset index`. Do not edit.\n") {
		t.Errorf("the index should say it is generated:\n%s", out)
	}
	idx, err := registry.ParseIndex([]byte(out))
	if err != nil {
		t.Fatalf("the index does not load: %v\n%s", err, out)
	}
	if idx.Schema != registry.IndexSchema || idx.Ref != "3f2c1ab9d0e4" || len(idx.Presets) != 2 {
		t.Fatalf("index = %+v", idx)
	}
	if idx.Presets[0].Name != "bundler" || idx.Presets[1].Name != "stack" {
		t.Errorf("entries should be in name order: %+v", idx.Presets)
	}
	data, _ := os.ReadFile(filepath.Join(testPresetsDir(), "stack.yaml"))
	e := idx.Presets[1]
	if e.Title != "Test stack" || e.PresetSchema != 1 || e.Detect != `compose.contains("LARAVEL_SAIL")` || e.SHA256 != registry.Sum(data) {
		t.Errorf("stack entry = %+v", e)
	}
}

func TestPresetIndexRefusesWhatItCannotDescribe(t *testing.T) {
	if _, err := execute(t, newPresetCmd(presetBackend{}), "preset", "index", testPresetsDir()); err == nil || !strings.Contains(err.Error(), "--ref") {
		t.Errorf("expected --ref to be required, got %v", err)
	}
	if _, err := execute(t, newPresetCmd(presetBackend{}), "preset", "index", testPresetsDir(), "--ref", "main"); err == nil || !strings.Contains(err.Error(), "not a commit") {
		t.Errorf("expected a ref error, got %v", err)
	}

	dir := t.TempDir()
	if _, err := execute(t, newPresetCmd(presetBackend{}), "preset", "index", dir, "--ref", "3f2c1ab9d0e4"); err == nil || !strings.Contains(err.Error(), "no preset files") {
		t.Errorf("expected an error for an empty directory, got %v", err)
	}
	os.WriteFile(filepath.Join(dir, "good.yaml"), []byte("schema: 1\nname: good\ntitle: Good\ndetect: 'true'\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "bad.yaml"), []byte("schema: 1\nname: bad\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "worse.yaml"), []byte("schema: 1\nname: worse\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "README.md"), []byte("not a preset"), 0o644)
	out, err := execute(t, newPresetCmd(presetBackend{}), "preset", "index", dir, "--ref", "3f2c1ab9d0e4")
	if err == nil || !strings.Contains(err.Error(), "bad.yaml") || !strings.Contains(err.Error(), "worse.yaml") {
		t.Errorf("expected every bad preset to be named, got %v", err)
	}
	if strings.Contains(out, "schema:") {
		t.Errorf("no index may be printed when a preset is invalid:\n%s", out)
	}
}
