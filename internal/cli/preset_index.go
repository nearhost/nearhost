package cli

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"gopkg.in/yaml.v3"

	"github.com/nearhost/nearhost/internal/preset"
	"github.com/nearhost/nearhost/internal/registry"
)

func newPresetIndexCmd() *cobra.Command {
	var ref string
	cmd := &cobra.Command{
		Use:   "index <dir>",
		Short: "Print the registry index for a directory of preset files",
		Long: "Read every <name>.yaml in <dir>, check it, and print the index a registry\n" +
			"serves: each preset's name, title, detect expression and hash, and the\n" +
			"commit the files are served from. Nothing is printed unless every preset\n" +
			"is valid.",
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if ref == "" {
				return errors.New("--ref is required: the commit the preset files are served from")
			}
			files, err := filepath.Glob(filepath.Join(args[0], "*.yaml"))
			if err != nil {
				return err
			}
			if len(files) == 0 {
				return fmt.Errorf("no preset files in %s", args[0])
			}
			sort.Strings(files)
			idx := registry.Index{Schema: registry.IndexSchema, Ref: ref}
			var errs []error
			for _, file := range files {
				data, err := os.ReadFile(file)
				if err != nil {
					errs = append(errs, err)
					continue
				}
				p, err := preset.Parse(strings.TrimSuffix(filepath.Base(file), ".yaml"), data)
				if err != nil {
					errs = append(errs, err)
					continue
				}
				idx.Presets = append(idx.Presets, registry.Entry{
					Name: p.Name, Title: p.Title, Description: p.Description,
					PresetSchema: p.Schema, Detect: p.Detect, SHA256: registry.Sum(data),
				})
			}
			if len(errs) > 0 {
				return errors.Join(errs...)
			}
			out, err := yaml.Marshal(idx)
			if err != nil {
				return err
			}
			// What is printed must be what a client will accept.
			if _, err := registry.ParseIndex(out); err != nil {
				return err
			}
			_, err = fmt.Fprintf(cmd.OutOrStdout(), "# Generated by `nearhost preset index`. Do not edit.\n%s", out)
			return err
		},
	}
	cmd.Flags().StringVar(&ref, "ref", "", "commit the preset files are served from")
	return cmd
}
